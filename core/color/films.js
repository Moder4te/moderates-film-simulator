/**
 * 필름 정의 데이터.
 *
 * 특성곡선은 **제조사 TDS PDF의 벡터 좌표를 직접 읽어** 전사한 실측값이다.
 * 그래프를 눈으로 디지타이징한 것이 아니라 PDF 안의 곡선 경로 좌표를 축 기하로
 * 변환한 것이라 재현 가능하고 정밀하다. 독립 시각 판독 3건과 농도 0.01 이내로
 * 일치하는 것을 확인했다.
 *
 * 출처 문서 자체(PDF)는 저작물이므로 저장소에 넣지 않는다. 여기 담긴 것은
 * 그래프에서 읽어낸 **수치 데이터**이며, source 필드에 출처를 기록한다.
 *
 * 곡선 축:
 *   x = 상대 로그 노광 H. TDS의 "Log H Ref"를 H=0으로 잡는다.
 *       (Portra 400은 절대 logE -1.44, Gold 200은 -1.14가 H=0)
 *   y = 현상된 네거티브의 농도 D (Status M), 주광 노광.
 *
 * 데이터 범위 밖(H < 시작점)은 curve.js가 발끝 기울기로 선형 외삽한다.
 * 발끝은 이미 평탄하므로 값이 발산하지 않는다.
 */

/** [H, D] 쌍으로 묶는다. hs와 ds는 길이가 같아야 한다. */
function curve(hs, ds) {
  if (hs.length !== ds.length) throw new Error("곡선 샘플 길이 불일치");
  return hs.map((h, i) => [h, ds[i]]);
}

